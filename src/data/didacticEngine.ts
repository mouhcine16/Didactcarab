function explainOption(
  q: RawQuestionItem,
  optKey: OptionKey,
  optText: string
): string {
  const isCorrect = q.correctAnswer === optKey;
  if (isCorrect) {
    return `✓ الصحيح: "${optText}" — ${q.officialExplanation}`;
  }

  if (optKey === 'E' && optText.includes('جميع الاختيارات المقترحة خاطئة')) {
    return `خاطئ (مموه): هذا الاختيار غير صائب هنا لأن الاختيار (${q.correctAnswer}) يمثل الجواب الصحيح المطابق للتوجيهات التربوية الرسمية في هذا السؤال.`;
  }

  for (const rule of DIDACTIC_CONCEPT_RULES) {
    if (rule.keywords.some((kw) => optText.includes(kw))) {
      return `خاطئ (مموه): "${optText}" — ${rule.definition} بينما يركز السؤال الحالي على: (${q.options[q.correctAnswer]}).`;
    }
  }

  if (q.isTextQuestion) {
    return `خاطئ (مموه): "${optText}" — فكرة جزئية أو غير مطابقة لمنطوق نص الانطلاق في الفقرة المستهدفة؛ إذ إن الجواب الدقيق وفق النص هو (${q.options[q.correctAnswer]}).`;
  }

  return `خاطئ (مموه): "${optText}" — مموه ديدكتيكي يخلط بين عناصر أو محطات منهجية مختلفة عن المطلوب في منطوق السؤال، في حين أن المعطى الرسمي المطابق لوثيقة التوجيهات التربوية هو (${q.options[q.correctAnswer]}).`;
}

export function enrichQuestion(q: RawQuestionItem): EnrichedQuestionItem {
  const breakdowns: OptionBreakdownMap = {
    A: q.optionBreakdowns?.A || explainOption(q, 'A', q.options.A),
    B: q.optionBreakdowns?.B || explainOption(q, 'B', q.options.B),
    C: q.optionBreakdowns?.C || explainOption(q, 'C', q.options.C),
    D: q.optionBreakdowns?.D || explainOption(q, 'D', q.options.D),
  };

  if (q.options.E) {
    breakdowns.E = q.optionBreakdowns?.E || explainOption(q, 'E', q.options.E);
  }

  return {
    ...q,
    optionBreakdowns: breakdowns,
  };
}

