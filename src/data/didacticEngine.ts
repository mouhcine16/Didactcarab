/**
 * مولد الأسئلة العكسية والأفقية التفاعلية:
 * يحول أي مموه (Distractor) مختار إلى جواب صحيح داخل سؤال ديدكتيكي جديد كامل ومعلل
 */
export function generateReverseQuestion(
  sourceQuestion: EnrichedQuestionItem,
  selectedDistractorKey?: OptionKey | 'RANDOM'
): GeneratedReverseQuestion {
  const availableDistractors = (['A', 'B', 'C', 'D'] as OptionKey[]).filter(
    (k) => k !== sourceQuestion.correctAnswer
  );

  const targetKey: OptionKey =
    !selectedDistractorKey || selectedDistractorKey === 'RANDOM'
      ? availableDistractors[Math.floor(Math.random() * availableDistractors.length)]
      : selectedDistractorKey;

  const targetText = sourceQuestion.options[targetKey] || sourceQuestion.options.A;

  // البحث عن قاعدة ديدكتيكية مطابقة للمموه المختار لبناء سؤال عكسي أصيل
  const matchedRule = DIDACTIC_CONCEPT_RULES.find((rule) =>
    rule.keywords.some((kw) => targetText.includes(kw))
  );

  let questionStem: string;
  let explanation: string;

  if (matchedRule) {
    questionStem = `${matchedRule.reverseQuestionStem}`;
    explanation = `في هذا التدريب العكسي، تم تحويل المموه (${targetKey}: "${targetText}") إلى جواب صحيح؛ لأنه ${matchedRule.definition}`;
  } else if (sourceQuestion.isTextQuestion) {
    questionStem = `أيٌّ من العبارات والمفاهيم الآتية يُمثّل المموه الديدكتيكي (${targetKey}) الذي استُعمل لصرف الانتباه عن الفكرة الأصلية في السؤال (${sourceQuestion.id}) ويمكن توظيفه عنواناً فرعياً لمحور مستقل؟`;
    explanation = `في هذا التدريب الأفقي على سؤال النص (${sourceQuestion.id})، تم عزل المموه (${targetKey}: "${targetText}") وتمييز مجاله الدلالي المستقل عن الفكرة المركزية الأصلية (${sourceQuestion.options[sourceQuestion.correctAnswer]}).`;
  } else {
    questionStem = `في إطار التدريب العكسي والأفقي على مفاهيم "${sourceQuestion.category}"، أيٌّ من الاختيارات الآتية يُطابق المفهوم أو الإجراء الديدكتيكي المتمثل في: (${targetText.slice(0, 42)}${targetText.length > 42 ? '...' : ''}) عند توظيفه في سياقه البيداغوجي الصحيح؟`;
    explanation = `يهدف هذا السؤال العكسي إلى تثبيت التمييز الدقيق بين الجواب الأصلي للسؤال (${sourceQuestion.id}) وهو "${sourceQuestion.options[sourceQuestion.correctAnswer]}"، وبين المموه (${targetKey}) وهو "${targetText}" حتى لا يلتبس الأمر على المترشح في صيغ الأسئلة المتقاربة.`;
  }

  return {
    sourceQuestionId: sourceQuestion.id,
    targetDistractorKey: targetKey,
    targetDistractorText: targetText,
    questionStem,
    options: { ...sourceQuestion.options },
    correctOption: targetKey,
    explanation,
  };
}
